#!/usr/bin/env python3
"""D.16 (logbook 239, the owner 2026-09-29): status.md is generated from context.md and the store row; context.md is
the only file a human or a session edits. Deterministic: no clock, only the dates context.md carries.
Usage: gen-status.py <task_dir> [--store <db>] [--check]
  prints status.md to stdout; --check exits 1 when <task_dir>/status.md differs from a fresh generation
  or when context.md state and the store status disagree (closed <-> done|declined)."""
import json, sqlite3, subprocess, sys

MARK = '<!-- generated by gen-status.py from context.md and the store; edit context.md, never this file -->'
args = sys.argv[1:]
check = '--check' in args
store = args[args.index('--store') + 1] if '--store' in args else '/Users/you/work/umbrella/.devwork/brain.db'
task_dir = [a for a in args if not a.startswith('--') and a != store][0].rstrip('/')

fm = json.loads(subprocess.run(['yq', '--front-matter=extract', '-o=json', '.', f'{task_dir}/context.md'],
                              capture_output=True, text=True, check=True).stdout)
tid = fm['task_id']
db = sqlite3.connect(f'file:{store}?mode=ro', uri=True)
row = db.execute("SELECT status, status_detail FROM record WHERE type='task' AND id=?", (tid,)).fetchone()
tickets = [t for (t,) in db.execute("SELECT to_id FROM edge WHERE from_id=? AND rel='about' AND to_id LIKE 'ticket:%' ORDER BY to_id", (f'task:{tid}',))]
world = [t for (t,) in db.execute("SELECT to_id FROM edge WHERE from_id=? AND rel='part_of' ORDER BY to_id", (f'task:{tid}',))]
status, detail = row if row else ('no store row', None)

v = lambda k: fm.get(k) or '—'
lines = [MARK, '', f'# {tid} — status', '',
         f'> {fm["role"]}', '',
         f'**Para:** {fm["para"]}', '',
         '| | |', '|---|---|',
         f'| state | `{fm["state"]}` · store `{status}` |',
         f'| ticket | {v("ticket_ref")} · store {", ".join(t[7:] for t in tickets) or "—"} |',
         f'| world | {fm["project_id"]} · store {", ".join(world) or "—"} |',
         f'| updated | {fm["updated"]} (created {fm["created"]}) |', '',
         f'**Where we are.** {fm["where_we_are"]}', '',
         f'**Next step.** {v("next_step")}', '',
         f'**Done when.** {v("done_when")}', '',
         f'**Waiting on.** {v("waiting_on")}', '']
if detail:
    lines += [f'**Store detail.** {detail.split(" || ")[0]}', '']
lines += ['Source: `context.md` · ledger: `logbook.jsonl`.', '']
out = '\n'.join(lines)

if not check:
    sys.stdout.write(out)
    sys.exit(0)
bad = []
try:
    if open(f'{task_dir}/status.md', encoding='utf-8').read() != out:
        bad.append('status.md differs from a fresh generation')
except FileNotFoundError:
    bad.append('status.md absent')
closed_store = status in ('done', 'declined')
if (fm['state'] == 'closed') != closed_store or (status == 'SIN DATOS'):
    bad.append(f'context.md state {fm["state"]} disagrees with store status {status}')
if fm['project_id'] != 'devwork-infra' and world != [fm['project_id']]:
    bad.append(f'context.md project_id {fm["project_id"]} disagrees with store part_of {world}')
for b in bad:
    print(f'[FAIL] {tid}: {b}')
if not bad:
    print(f'[OK] {tid}: status.md generated, state {fm["state"]} agrees with store {status}')
sys.exit(1 if bad else 0)
